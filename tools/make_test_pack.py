#!/usr/bin/env python3
"""Makes a tiny optional pack, with its archive and index, to try installing packs in
usdcc without a release (docs/USD_PLUGINS.md section 10).

  python tools/make_test_pack.py <folder> --version 26.12.1 [--version 26.12.2 ...] [--name hello]
                                 [--change 26.12.2] [--platform linux-x64]

The pack has no binaries, so it is the same on every platform: a codeless schema whose
prim type, UsdccHelloThing, exists only while the pack is loaded. `<folder>` then holds
what a release would attach for each version, and usdcc reads it with

  USDCC_PACKS_URL=<folder>

`--change <version>` gives that version's pack one more file, so its content differs from
the others': an update to it has to download, where otherwise it copies.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "ci"))
import pack_index  # noqa: E402

PLUG_INFO = {
    "Plugins": [{
        "Info": {"Types": {"UsdccHelloPackUsdccHelloThing": {
            "alias": {"UsdSchemaBase": "UsdccHelloThing"},
            "autoGenerated": True,
            "bases": ["UsdTyped"],
            "schemaIdentifier": "UsdccHelloThing",
            "schemaKind": "concreteTyped",
        }}},
        "LibraryPath": "",
        "Name": "usdccHelloPack",
        "ResourcePath": ".",
        "Root": ".",
        "Type": "resource",
    }]
}

SCHEMA = '''#usda 1.0
(
    "WARNING: THIS FILE IS GENERATED BY usdGenSchema.  DO NOT EDIT."
)

class UsdccHelloThing "UsdccHelloThing" (
    customData = {
        string userDocBrief = "A prim type only the hello test pack has."
    }
)
{
    string usdccHello:greeting = "hello"
}
'''


def _write(file, text):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(text, encoding="utf-8", newline="\n")


def make_pack(parent, name, changed=False):
    """The pack's folder, <parent>/<name>, laid out as usdcc installs one."""
    pack = Path(parent) / name
    if pack.exists():
        shutil.rmtree(pack)
    _write(pack / "usdcc-plugin.json", json.dumps({
        "id": f"org.usdcc.pack.{name}", "name": f"{name.capitalize()} (test pack)", "version": "1.0.0",
        "description": "A prim type, to try installing packs with.", "api": 1, "usd": ["plugin/usd"]}, indent=2) + "\n")
    _write(pack / "plugin/usd/plugInfo.json", '{\n    "Includes": [ "*/resources/" ]\n}\n')
    _write(pack / "plugin/usd/usdccHelloPack/resources/plugInfo.json", json.dumps(PLUG_INFO, indent=4) + "\n")
    _write(pack / "plugin/usd/usdccHelloPack/resources/generatedSchema.usda", SCHEMA)
    _write(pack / "licenses/LICENSE.txt", "A test pack of usdcc's own (BSD-3-Clause, as usdcc).\n")
    if changed:
        _write(pack / "plugin/usd/usdccHelloPack/resources/changed.txt", "This build of the pack differs.\n")
    return pack


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("folder", type=Path, help="where the archives and indexes go")
    parser.add_argument("--version", action="append", required=True, help="a usdcc version to make it for; repeatable")
    parser.add_argument("--name", default="hello")
    parser.add_argument("--change", action="append", default=[], metavar="VERSION",
                        help="a version whose pack gets another file; repeatable")
    parser.add_argument("--platform", default=pack_index.release_platform())
    args = parser.parse_args(argv)

    shown = {"title": f"{args.name.capitalize()} (test pack)", "description": "A prim type, to try installing packs with.",
             "license": "BSD-3-Clause", "homepage": "https://github.com/olihey/usdcc", "renderers": []}
    with tempfile.TemporaryDirectory(prefix="usdcc-test-pack-") as work:
        for version in args.version:
            pack = make_pack(work, args.name, changed=version in args.change)
            archive = pack_index.make_archive(pack, args.folder / pack_index.archive_name(version, args.platform, args.name))
            item = pack_index.entry(pack, archive, shown)
            index = pack_index.write_index(args.folder, version, args.platform, [item])
            print(f"{index.name}: {item['file']}, content {item['content'][:12]}")
    print(f"USDCC_PACKS_URL={args.folder.resolve()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
