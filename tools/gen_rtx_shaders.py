"""Compiles the RTX plugin's shaders to SPIR-V headers that are checked in.

    python tools/gen_rtx_shaders.py

Needs glslc from the Vulkan SDK (VULKAN_SDK, or on PATH). The build itself doesn't:
it uses the headers this writes (src/plugins/rtx_render_native/shaders/*_spv.h).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "src" / "plugins" / "rtx_render_native" / "shaders"


def glslc() -> str:
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        for name in ("glslc.exe", "glslc"):
            candidate = Path(sdk) / "Bin" / name
            if candidate.exists():
                return str(candidate)
    found = shutil.which("glslc")
    if not found:
        sys.exit("glslc not found: install the Vulkan SDK or put glslc on PATH")
    return found


def compile_shader(source: Path) -> None:
    stem = source.name.replace(".", "_")
    with tempfile.TemporaryDirectory() as folder:
        spirv = Path(folder) / (stem + ".spv")
        subprocess.run([glslc(), "-O", "--target-env=vulkan1.2", str(source), "-o", str(spirv)], check=True)
        data = spirv.read_bytes()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = [", ".join("0x%08x" % w for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    name = "k" + "".join(part.capitalize() for part in stem.split("_")) + "Spirv"
    header = SHADERS / (stem + "_spv.h")
    header.write_text(
        "// Generated by tools/gen_rtx_shaders.py from %s; don't edit.\n"
        "#pragma once\n#include <cstdint>\n\n"
        "inline constexpr uint32_t %s[] = {\n    %s,\n};\n" % (source.name, name, ",\n    ".join(lines)),
        encoding="utf-8",
        newline="\n",
    )
    print("%s -> %s (%d words)" % (source.name, header.name, len(words)))


if __name__ == "__main__":
    for shader in sorted(SHADERS.glob("*.comp")):
        compile_shader(shader)
