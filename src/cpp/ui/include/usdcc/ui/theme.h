#pragma once

#include "usdcc/core/toast.h"

#include <QColor>
#include <QIcon>
#include <QString>
#include <QStringList>

#include <functional>

class QApplication;
class QImage;
class QObject;

namespace ads {
class CDockManager;
}

// The application's themes (docs/THEMES.md): named colours ("tokens") that the
// stylesheets, the QPalette and custom painting all take from here.
namespace usdcc::ui::theme {

// The usdcc app icon (three stacked blue layers), as a multi-size QIcon.
// apply() installs it as the application's window icon, which is what the
// title bar logo and the taskbar show while the app runs; the .exe's own
// icon (Explorer, pinned shortcuts) comes from src/cpp/app/resources/usdcc.ico.
// Both are generated by tools/gen_app_icon.py.
QIcon appIcon();

// The Appearance/theme setting: a theme's name (themeNames()).
inline constexpr auto themeKey = "Appearance/theme";
inline constexpr auto defaultThemeName = "usdcc Dark";
inline constexpr auto lightThemeName = "usdcc Light";
// Not a theme of its own: usdcc Dark or usdcc Light, as the system is.
inline constexpr auto systemThemeName = "System";

// The Appearance/accentColor setting (usdcc::core::Settings): the colour of
// selections, checked buttons, focus borders and links. Its default is the
// current theme's own accent.
inline constexpr auto accentColorKey = "Appearance/accentColor";
inline constexpr auto defaultAccentColor = "#3d8bfd";

// What a colour is for. theme.cpp's table has each one's name (in stylesheets
// and theme files) and its colour in usdcc Dark and usdcc Light.
enum class Token {
    SurfaceBar,
    SurfaceToolbar,
    SurfacePanel,
    SurfaceRaised,
    SurfaceHover,
    SurfaceReadOnly,
    Inset,
    Gap,
    BevelLight,
    BevelMidlight,
    BevelMid,
    Shadow,
    Text,
    TextStrong,
    Ink,      // text, at an alpha
    Overlay,  // hairlines and hover fills, at an alpha
    Muted,
    MutedStrong,
    Icon,
    IconDisabled,
    IconGrip,
    Accent,
    AccentText,
    OnAccent,
    Error,
    Warning,
    Attention,
    Success,
    SyntaxKeyword,
    SyntaxBuiltin,
    SyntaxString,
    SyntaxNumber,
    SyntaxPath,
    SyntaxKey,
    PrimInstance,
    PrimArcs,
    PrimPrototype,
    GraphGridFine,
    GraphGridCoarse,
    GraphConnection,
    NodeBody,
    NodePage,
    NodeBorder,
    NodeBorderHover,
    NodeText,
    NodeTextMuted,
    NodePageText,
    Count,
};

// The current theme's colour for `token`, at `alpha` (0-255). Look it up when
// drawing rather than keeping it; what has to keep one follows onChanged().
QColor color(Token token, int alpha = 255);

// The name a stylesheet or a theme file uses: "surface-panel".
QString tokenName(Token token);

// The themes to choose from: System, the built-in ones and the user's own
// (*.json in userThemesFolder()).
QStringList themeNames();
QString userThemesFolder();
// The theme in use, with System resolved.
QString currentThemeName();
bool isDark();

// Reads a theme file. False, with why, if it isn't one: no JSON object, no name, a "base" other
// than dark or light, an unknown token or a colour that isn't "#rrggbb". What it doesn't name is
// its base's.
bool readThemeFile(const QString& path, QString* name, QString* error);

// Calls `changed` after the theme or the accent has changed and the stylesheets
// and palette are applied, for as long as `owner` lives. Returns the
// connection, a child of `owner`; deleting it disconnects.
QObject* onChanged(QObject* owner, std::function<void()> changed);

// The icon at `path` (":/usdcc/theme/trash.png") in the theme's colours: the
// grey line icons take Token::Icon, the white ones Token::OnAccent. It draws
// itself in the colours of the moment, so it follows a theme change.
QIcon icon(const QString& path);
// With one for State::On, in Token::OnAccent: a button's that is filled with the
// accent when checked. Not for tabs and tree items: selected and open ones are On too.
QIcon icon(const QString& path, const QString& onPath);
// The image recoloured as icon() does.
QImage tintedImage(const QString& path);

// Defines the theme's settings in Settings::instance() (apply() does this).
void defineSettings();

// The current accent colour (the theme's unless the setting says otherwise).
QColor accent();

// A toast notification's colour (docs/NOTIFICATIONS.md): Info the accent,
// Success green, Warning amber, Error red.
QColor toastColor(core::ToastKind kind);

// `sheet` with the stylesheet tokens replaced by the current theme's colours and
// `accentColor`: @token by the colour itself, @token-rgb by "r, g, b" (for
// rgba(@accent-rgb, 25%)). @accent-hover is the accent, a little lighter.
QString resolveTokens(const QString& sheet, const QColor& accentColor);

// The application's theme (see docs/THEMES.md): the Fusion style with the
// theme's palette, plus the app-wide stylesheet from
// resources/theme/app.qss. Call once, right after constructing the
// QApplication and before creating any widgets. Follows UI scale, theme and
// accent colour changes from then on.
void apply(QApplication& app);

// ADS gives its dock manager its own widget-level stylesheet, which beats
// the app-wide one for the properties it sets — so the tabs, title bars and
// splitter handles need a second pass. Appends resources/theme/dock.qss to
// the manager's existing stylesheet. Call right after constructing the
// manager.
void applyToDockManager(ads::CDockManager* dockManager);

}  // namespace usdcc::ui::theme
